CREATE TABLE spot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    localizacao GEOMETRY(Point, 4326) NOT NULL
);

-- 1. Índice Espacial (Obrigatório para performance!)
CREATE INDEX idx_spot_localizacao ON spot USING GIST (localizacao);

-- 2. Constraint de nome (Segurança de dados)
ALTER TABLE spot ALTER COLUMN nome SET NOT NULL;